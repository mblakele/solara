# ── Quirks ───────────────────────────────────────────────────────────────

class TestQuirks:
    """The three quirks the refactor must preserve (plus the C==1/R==1 fix)."""

    def test_quirk_1_c1_r1_inside_window(self):
        """Quirk 1 (fixed): C=1, R=1 inside window → credit 0, C stays 1."""
        tracker = _tracker(window_secs=60)
        tracker.effects.add(_settle_effect(age_secs=10))
        tracker.record_command(1)
        result = tracker.inflight_wh(1, SECONDS_REMAINING_900, FIXED_NOW)
        assert result == 0.0
        assert tracker.last_commanded_amps == 1

    def test_quirk_1_c1_r1_outside_window(self):
        """Quirk 1 (fixed): C=1, R=1 outside window → credit 0, C stays 1."""
        tracker = _tracker(window_secs=60)
        tracker.effects.add(_settle_effect(age_secs=200))
        tracker.record_command(1)
        result = tracker.inflight_wh(1, SECONDS_REMAINING_900, FIXED_NOW)
        assert result == 0.0
        assert tracker.last_commanded_amps == 1

    def test_quirk_none_report_between_zeros(self):
        """Quirk 2: a None report does not reset the zero counter."""
        tracker = _tracker()
        tracker.record_command(18)
        # First zero → counter becomes 1.
        tracker.inflight_wh(0, SECONDS_REMAINING_900, FIXED_NOW)
        assert tracker._zero_amp_samples == 1
        # None report → counter stays at 1 (not reset).
        tracker.inflight_wh(None, SECONDS_REMAINING_900, FIXED_NOW)
        assert tracker._zero_amp_samples == 1
        # Second zero → counter becomes 2 → clear.
        result = tracker.inflight_wh(0, SECONDS_REMAINING_900, FIXED_NOW)
        assert result == 0.0
        assert tracker.last_commanded_amps is None

    def test_quirk_turn_on_effect_as_newest_tesla(self):
        """Quirk 3: a turn_on effect is the newest Tesla effect on the 1 A path.

        Wall age = 200s > window=60s, data-point age = 200s > window=60s,
        so the command clears (same as row 7).
        """
        tracker = _tracker(window_secs=60)
        # Only a turn_on effect — no set_amps settle.
        tracker.effects.add(_turn_on_effect(age_secs=200))
        tracker.record_command(18)
        result = tracker.inflight_wh(1, SECONDS_REMAINING_900, FIXED_NOW)
        assert result == 0.0
        assert tracker.last_commanded_amps is None


