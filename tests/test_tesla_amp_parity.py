class TestExpiryAges:
    """Wall-clock expiry with a fresh data-point clock, and the reverse."""

    def test_wall_expired_data_point_fresh(self):
        """R==1, wall expired but data point fresh → credit C-1 (row 6)."""
        tracker = _tracker(window_secs=30)
        effect = PendingEffect(
            device_name="tesla",
            action="set_amps",
            timestamp=FIXED_NOW - timedelta(seconds=200),
            data_point_at=FIXED_NOW - timedelta(seconds=10),
            power_watts=0,
            target_amps=18,
            direction="increase",  # type: ignore[arg-type]
            qh_name="QH1",
        )
        tracker.effects.add(effect)
        tracker.record_command(18)
        result = tracker.inflight_wh(
            1, SECONDS_REMAINING_600, FIXED_NOW,
            data_point_at=FIXED_NOW - timedelta(seconds=10),
        )
        assert result == WH_C17_R1_S600

    def test_wall_fresh_credits_even_when_dp_expired(self):
        """R==1, wall fresh (elapsed < window) → credit C-1 regardless of dp age.

        The _inflight_one_amp() code checks wall-clock first; if elapsed_wall
        < window it credits immediately without looking at data-point-at age.
        So "wall fresh + dp expired" does NOT clear — it credits.
        """
        tracker = _tracker(window_secs=30)
        effect = PendingEffect(
            device_name="tesla",
            action="set_amps",
            timestamp=FIXED_NOW - timedelta(seconds=10),   # wall age 10 < window 30
            data_point_at=FIXED_NOW - timedelta(seconds=200),
            power_watts=0,
            target_amps=18,
            direction="increase",  # type: ignore[arg-type]
            qh_name="QH1",
        )
        tracker.effects.add(effect)
        tracker.record_command(18)
        result = tracker.inflight_wh(
            1, SECONDS_REMAINING_900, FIXED_NOW,
            data_point_at=FIXED_NOW - timedelta(seconds=10),
        )
        # Wall check passes → credits C-1 even though dp age = 190 > window.
        assert result == WH_C17_R1_S900


# ── current_qh does not affect inflight_wh() ─────────────────────────────

class TestQHIndependence:
    """inflight_wh() never receives current_qh — it must be QH-independent."""

    def test_inflight_wh_same_across_qh(self):
        """Same C, R, seconds → same Wh regardless of which QH the effect is in."""
        tracker = _tracker()
        tracker.record_command(18)
        # inflight_wh does not accept current_qh.
        result_a = tracker.inflight_wh(10, SECONDS_REMAINING_900, FIXED_NOW)
        assert result_a == 480.0

    def test_state_tracker_is_settling_respects_qh(self):
        """StateTracker.is_settling() does respect QH — but inflight_wh() doesn't use it."""
        tracker = StateTracker(prediction_window_seconds=30)
        effect = PendingEffect(
            device_name="tesla",
            action="set_amps",
            timestamp=FIXED_NOW - timedelta(seconds=10),
            data_point_at=FIXED_NOW - timedelta(seconds=10),
            power_watts=0,
            target_amps=18,
            direction="increase",  # type: ignore[arg-type]
            qh_name="QH2",
        )
        tracker.add_effect(effect)
        # is_settling with a different QH → False (QH-boundary expiry).
        assert tracker.is_settling(FIXED_NOW, current_qh="QH1") is False
        # But inflight_wh() doesn't pass current_qh — it uses is_settling()
        # without direction constraints for the settle-expired gate.


# ── Orphan guard ─────────────────────────────────────────────────────────

class TestOrphanGuard:
    """After prune_old_effects() removes the last set_amps effect,
    last_commanded_amps is None."""

    def test_prune_clears_last_commanded_amps(self):
        """Orphan guard: pruning the last set_amps effect clears C.

        Uses a recent current data_point_at (-10s) so the effect's dp at -200s
        is old on both wall-clock and data-point measures, triggering prune.
        """
        tracker = StateTracker(prediction_window_seconds=30)
        effect = PendingEffect(
            device_name="tesla",
            action="set_amps",
            timestamp=FIXED_NOW - timedelta(seconds=200),
            data_point_at=FIXED_NOW - timedelta(seconds=200),
            power_watts=0,
            target_amps=18,
            direction="increase",  # type: ignore[arg-type]
            qh_name="QH1",
        )
        tracker.add_effect(effect)
        tracker.last_commanded_amps = 18
        assert tracker.last_commanded_amps == 18
        # Prune with a recent data_point_at so the effect is old by both measures.
        tracker.prune_old_effects(
            data_point_at=FIXED_NOW - timedelta(seconds=10),
            now=FIXED_NOW,
        )
        # Orphan guard fired: last_commanded_amps cleared.
        assert tracker.last_commanded_amps is None

    def test_prune_does_not_clear_with_surviving_set_amps(self):
        """Orphan guard does not fire when a set_amps effect survives."""
        tracker = StateTracker(prediction_window_seconds=30)
        old_set = PendingEffect(
            device_name="tesla",
            action="set_amps",
            timestamp=FIXED_NOW - timedelta(seconds=200),
            data_point_at=FIXED_NOW - timedelta(seconds=200),
            power_watts=0,
            target_amps=18,
            direction="increase",  # type: ignore[arg-type]
            qh_name="QH1",
        )
        # Fresh set_amps survives wall cutoff (-30s): -10 > -30.
        fresh_set = PendingEffect(
            device_name="tesla",
            action="set_amps",
            timestamp=FIXED_NOW - timedelta(seconds=10),
            data_point_at=FIXED_NOW - timedelta(seconds=200),
            power_watts=0,
            target_amps=5,
            direction="decrease",  # type: ignore[arg-type]
            qh_name="QH1",
        )
        tracker.add_effect(old_set)
        tracker.add_effect(fresh_set)
        tracker.last_commanded_amps = 18
        tracker.prune_old_effects(
            data_point_at=FIXED_NOW - timedelta(seconds=10),
            now=FIXED_NOW,
        )
        # The fresh set_amps survives — orphan guard does not fire.
        assert tracker.last_commanded_amps == 18
